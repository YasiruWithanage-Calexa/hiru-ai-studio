"""The developer's commands beyond make and check (plan/2026-11-03 Phase 7): draw a graph, write the catalog, open the
systems in LangGraph Studio, and remove a part with every reference to it.

    hiru-ai graph <id>            a system or panel as Mermaid text
    hiru-ai catalog [--check]     docs/AI_CATALOG.md: every part, who owns it, its tier, tools, knowledge, who uses it
    hiru-ai studio                langgraph.json, so `langgraph dev` opens each system and panel
    hiru-ai remove <kind> <id>    what would go; with --yes, the references and then the folder
    hiru-ai remove --group <id>   a whole group (agents/adam/, ...): its folders, then what still names it
"""
from __future__ import annotations

import json
import os
import re
import shutil
from pathlib import Path

from hiru_ai.core import manifest as mf
from hiru_ai.core.errors import HiruAIError
from hiru_ai.core.patterns import mermaid
from hiru_ai.core.registry import Registry

CATALOG = Path("docs") / "AI_CATALOG.md"
STUDIO = "langgraph.json"


def draw(reg: Registry, ident: str) -> str:
    """The wiring of the system or panel `ident` (a system wins a name both share)."""
    for kind in ("system", "panel"):
        if (kind, ident) in reg.components:
            module = reg.module(kind, ident, "graph")
            return mermaid(module.blank(reg))
    raise HiruAIError(f"no system or panel {ident!r}")


def _cell(items: list[str]) -> str:
    return ", ".join(sorted(items)) or "-"


def catalog(reg: Registry) -> str:
    """Every part as a table per kind. Generated: edit a manifest, not this file (CI checks it is current)."""
    out = ["# AI catalog", "",
           "Generated by `hiru-ai catalog` from every `component.yaml`; do not edit by hand. "
           "CI fails when it is out of date.", ""]
    for kind in mf.KINDS:
        rows = sorted((i, c) for (k, i), c in reg.components.items() if k == kind)
        if not rows:
            continue
        # a tool's row says what a call may change (read / stage / write); an agent's, its tier (and a tools form)
        third = "effect" if kind == "tool" else "tier"
        out += [f"## {kind}s ({len(rows)})", "", f"| id | status | owner | {third} | uses | used by | summary |",
                "|---|---|---|---|---|---|---|"]
        for ident, comp in rows:
            m = comp.manifest
            uses = [f"{k}:{i}" for k, i in m.refs()]
            used_by = [f"{k}:{i}" for k, i in reg.refs_to(kind, ident)]
            tier = getattr(m, "model", "") if kind == "agent" else getattr(m, "effect", "") if kind == "tool" else ""
            if kind == "agent" and getattr(m, "with_tools", None):  # the form AGENT_TOOLS switches on
                tier += " + tools form"
            out.append(f"| `{ident}` | {m.status} | {m.owner or '-'} | {tier or '-'} | {_cell(uses)} | "
                       f"{_cell(used_by)} | {m.summary.replace('|', '/')} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def studio(reg: Registry) -> str:
    """`langgraph.json` for LangGraph Studio: each system and panel is a graph built with in-memory ports, so a person
    steps through the wiring locally. The factory is the part's own `blank()`."""
    graphs = {}
    for kind in ("system", "panel"):
        for (k, ident), comp in sorted(reg.components.items()):
            if k == kind and (comp.folder / "graph.py").is_file():
                graphs[ident] = f"./{comp.folder.relative_to(reg.root.parents[2]).as_posix()}/graph.py:blank"
    return json.dumps({"dependencies": ["."], "graphs": graphs, "env": "./.env"}, indent=2) + "\n"


# ── remove ──────────────────────────────────────────────────────────────────────────────────────────────────────────


def _ref_forms(kind: str, ident: str) -> list[str]:
    return [ident, f"{kind}:{ident}"]


def removal_plan(reg: Registry, kind: str, ident: str) -> tuple[list[str], list[str]]:
    """-> (references a person must remove by hand: roles a part cannot work without, each as "kind id: why", and the
    manifests whose lists name it, which `--yes` edits)."""
    if (kind, ident) not in reg.components:
        raise HiruAIError(f"no {kind} {ident!r}")
    by_hand, listed = [], []
    for rk, ri in reg.refs_to(kind, ident):
        comp = reg.components[(rk, ri)]
        text = (comp.folder / "component.yaml").read_text(encoding="utf-8")
        if re.search(rf"^(?!\s*#)\s*(judge|reviser|writer|critic|settle)\s*:\s*{kind}:{ident}\s*$", text, re.M):
            by_hand.append(f"{rk} {ri}: {kind}:{ident} is a role it cannot work without; choose another first")
        else:
            listed.append(f"{rk}:{ri}")
    return by_hand, listed


def _strip(text: str, kind: str, ident: str) -> str:
    """The manifest without the references to the part: an entry in a flow list (`agents: [a, b]`), a member line of a
    panel, or a `review:` entry."""
    lines = []
    skipping = False
    for line in text.splitlines():
        body = line.split("#", 1)[0]
        if skipping:  # the rest of a member written over several lines, up to its closing brace
            skipping = "}" not in body
            continue
        if re.search(rf"^\s*-\s*\{{[^}}]*\bagent:\s*{ident}\b", body) and kind == "agent":
            skipping = "}" not in body
            continue  # a panel member
        if re.match(rf"^\s*-\s*{kind}:{ident}\s*$", body):
            continue  # a block-list reference
        flow = re.match(r"^(\s*[a-z_]+:\s*)\[(.*)\](\s*(#.*)?)$", line)
        if flow:
            drop = _ref_forms(kind, ident)
            keep = [x.strip() for x in flow.group(2).split(",") if x.strip() and x.strip() not in drop]
            line = f"{flow.group(1)}[{', '.join(keep)}]{flow.group(3)}"
        lines.append(line)
    return "\n".join(lines) + "\n"


def remove(reg: Registry, kind: str, ident: str, *, yes: bool) -> list[str]:
    """What was (or, without `yes`, would be) done, one line each. Refuses while a required role names the part."""
    by_hand, listed = removal_plan(reg, kind, ident)
    if by_hand:
        raise HiruAIError("cannot remove " + f"{kind} {ident}:\n  " + "\n  ".join(by_hand))
    done = [f"edit {ref} (drop its reference)" for ref in listed] + [f"delete {reg.components[(kind, ident)].folder}"]
    if not yes:
        return ["would " + line for line in done]
    for ref in listed:
        rk, ri = ref.split(":")
        path = reg.components[(rk, ri)].folder / "component.yaml"
        path.write_text(_strip(path.read_text(encoding="utf-8"), kind, ident), encoding="utf-8")
    shutil.rmtree(reg.components[(kind, ident)].folder)
    return done


# ── remove a whole group (plan/2026-11-04b §5.0 rule 6) ─────────────────────────────────────────────────────────────

_SCAN_SKIP = {".git", ".venv", "node_modules", "plan", ".idea", ".claude", ".mypy_cache", ".pytest_cache",
              ".ruff_cache", ".import_linter_cache", "hiru_ai_studio.egg-info"}
_SCAN_SUFFIX = {".py", ".yaml", ".yml", ".sql", ".ps1", ".md", ".toml", ".json", ".txt", ".sh", ".ts", ".tsx"}


def repo_root(reg: Registry) -> Path:
    """The repository the package lives in: `<repo>/src/libs/hiru_ai`, or the folder beside a test's `hiru_ai`."""
    return reg.root.parents[2] if reg.root.parent.name == "libs" else reg.root.parent


def group_folders(reg: Registry, group: str) -> list[Path]:
    """Every folder that goes with the group: its folder in each layer, then the repo folders its group.yaml lists
    (only those that exist; one that is not there yet is simply not part of the removal)."""
    layers = sorted(reg.root / layer / group for layer in mf.LAYERS.values() if (layer, group) in reg.groups)
    if not layers:
        raise HiruAIError(f"no group {group!r}; groups: {', '.join(sorted(reg.group_ids())) or 'none'}")
    repo = repo_root(reg)
    listed = [repo / rel for k in sorted(reg.groups) if k[1] == group for rel in reg.groups[k].folders]
    return layers + sorted({p for p in listed if p.exists() and p not in layers})


def group_references(reg: Registry, group: str) -> list[str]:
    """Files outside the group that still name it (`<group>_…` ids, `hiru_ai.<layer>.<group>`, `contracts.<group>`,
    `…_<group>` such as a function): what a person edits after the folders go. The group's own folders and the plans
    are not looked at."""
    own = [p.resolve() for p in group_folders(reg, group)]
    pattern = re.compile(rf"\b{group}_\w+|\w+_{group}\b|hiru_ai\.\w+\.{group}\b|contracts\.{group}\b")
    out: list[str] = []
    repo = repo_root(reg).resolve()
    for dirpath, dirnames, filenames in os.walk(repo):
        here = Path(dirpath).resolve()
        dirnames[:] = sorted(d for d in dirnames if d not in _SCAN_SKIP and d != "__pycache__"
                             and (here / d).resolve() not in own)
        for name in sorted(filenames):
            path = here / name
            if path.suffix not in _SCAN_SUFFIX or path.stat().st_size > 1_000_000:
                continue
            try:
                hit = pattern.search(path.read_text(encoding="utf-8", errors="ignore"))
            except OSError:
                continue
            if hit:
                out.append(f"{path.relative_to(repo).as_posix()}: names {hit.group(0)!r}")
    return out


def remove_group(reg: Registry, group: str, *, yes: bool) -> list[str]:
    """What was (or, without `yes`, would be) done, one line each. Folders go; references outside are only listed:
    each is a one-line edit a person makes (the migration is left alone, its columns just stay unused)."""
    folders = group_folders(reg, group)
    repo = repo_root(reg).resolve()
    shown = [f.resolve().relative_to(repo).as_posix() if f.resolve().is_relative_to(repo) else str(f) for f in folders]
    outside = [f"by hand: {text}" for k in sorted(reg.groups) if k[1] == group
               for text in reg.groups[k].outside]
    refs = group_references(reg, group)
    if yes:
        for folder in folders:
            shutil.rmtree(folder)
    verb = "" if yes else "would "
    return ([f"{verb}delete {rel}" for rel in shown] + outside
            + [f"still names the group, edit by hand: {r}" for r in refs])
