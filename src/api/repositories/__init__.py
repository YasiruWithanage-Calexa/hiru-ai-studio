"""All database access. Routers and services call these; nothing else talks to Supabase.

The API uses the service role, so RLS does not apply here: authorisation is enforced before a
repository is called (`api/deps/authz.py`). Rows are returned as plain dicts shaped like the
tables; routers turn them into `contracts` models.

`Repos` is a bundle of protocols so tests can swap the Supabase-backed implementation for
`tests/api/fakes.py` without patching anything.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from typing import Any, Protocol
from uuid import UUID

Row = dict[str, Any]
Rows = list[Row]  # for a class that has a method called `list`, where `list[...]` no longer means the type


class ProfilesRepo(Protocol):
    async def get(self, user_id: UUID) -> Row | None: ...
    async def get_by_email(self, email: str) -> Row | None: ...
    async def list(self) -> list[Row]: ...
    async def update(self, user_id: UUID, fields: Row) -> Row: ...
    async def count_active_admins(self) -> int: ...


class ProductionsRepo(Protocol):
    async def list_all(self) -> list[Row]: ...
    async def list_for_member(self, user_id: UUID) -> list[tuple[Row, str]]: ...
    async def get(self, production_id: UUID) -> Row | None: ...
    # The production and the user's role on it (None: not a member), in one read; None if missing.
    async def get_with_role(self, production_id: UUID, user_id: UUID) -> tuple[Row, str | None] | None: ...
    async def create(self, fields: Row) -> Row: ...
    async def update(self, production_id: UUID, fields: Row) -> Row: ...


class MembersRepo(Protocol):
    async def role_of(self, production_id: UUID, user_id: UUID) -> str | None: ...
    async def list(self, production_id: UUID) -> list[Row]: ...
    async def upsert(self, production_id: UUID, user_id: UUID, role: str, added_by: UUID) -> Row: ...
    async def delete(self, production_id: UUID, user_id: UUID) -> bool: ...


class InvitationsRepo(Protocol):
    async def create(self, fields: Row) -> Row: ...
    async def delete(self, invitation_id: UUID) -> None: ...
    async def list_pending(self) -> list[Row]: ...


class AuthAdmin(Protocol):
    async def invite(self, email: str, redirect_to: str, data: Row) -> None: ...


class AuditRepo(Protocol):
    async def record(
        self,
        *,
        action: str,
        entity: str,
        entity_id: str | None,
        actor_user_id: UUID | None,
        production_id: UUID | None = None,
        diff: Row | None = None,
        actor_agent: str | None = None,
    ) -> None: ...

    async def list(self, production_id: UUID, limit: int = 100) -> list[Row]: ...  # newest first


class JobsRepo(Protocol):
    async def create(self, fields: Row) -> Row: ...
    async def get(self, job_id: UUID) -> Row | None: ...
    async def mark_failed(self, job_id: UUID, error: str) -> None: ...
    async def events(self, job_id: UUID, after_seq: int = 0) -> list[Row]: ...
    async def latest(self, production_id: UUID, kind: str) -> Row | None: ...
    # Compare-and-set, so two deliveries of the same hand-off advance or resume a job once.
    async def advance(self, job_id: UUID, from_cursor: int, request: Row | None = None) -> bool: ...
    async def claim_resume(self, job_id: UUID) -> bool: ...
    # The sweeper's two reads (plan/2026-11-08c phase 5): jobs still pending/running whose row has not changed since
    # `before`, and when a job last wrote an event (None: never). Columns only: id, kind, production_id, status,
    # updated_at.
    async def active_before(self, before: datetime) -> list[Row]: ...
    async def last_event_at(self, job_id: UUID) -> datetime | None: ...
    # `live` (plan/2026-11-08c phase 3): ONE column-limited query for the status read: rows of the production that are
    # still active, plus (when `since` is given) any that changed after it. Never `*`, never a ticket.
    async def live(self, production_id: UUID, since: datetime | None) -> list[Row]: ...  # id, kind, status, updated_at


class DocumentsRepo(Protocol):
    async def create(self, fields: Row) -> Row: ...
    async def get(self, production_id: UUID, document_id: UUID) -> Row | None: ...
    async def find_by_hash(self, production_id: UUID, sha256: str) -> Row | None: ...
    async def list(self, production_id: UUID) -> list[Row]: ...
    async def update(self, document_id: UUID, fields: Row) -> Row: ...
    async def delete(self, document_id: UUID) -> None: ...
    # Documents still `processing` whose row has not changed since `before` (the sweeper; columns id, updated_at).
    async def processing_before(self, before: datetime) -> Rows: ...
    async def live(self, production_id: UUID, since: datetime | None) -> Rows: ...  # id, status, updated_at


class StorageRepo(Protocol):
    async def upload(self, bucket: str, path: str, data: bytes, content_type: str) -> None: ...
    async def remove(self, bucket: str, path: str) -> None: ...
    async def download(self, bucket: str, path: str) -> bytes: ...


class SearchRepo(Protocol):
    async def match_chunks(
        self,
        *,
        query_text: str,
        query_embedding: list[float] | None,
        production_id: UUID | None,
        corpora: list[str],
        document_ids: list[UUID] | None,
        match_count: int,
    ) -> list[Row]: ...

    async def match_techniques(
        self,
        *,
        query_text: str,
        query_embedding: list[float] | None,
        domain: str,
        categories: list[str] | None,
        match_count: int,
    ) -> list[Row]: ...


class EpisodesRepo(Protocol):
    async def list(self, production_id: UUID) -> list[Row]: ...
    async def get(self, production_id: UUID, episode_id: UUID) -> Row | None: ...
    async def update(self, episode_id: UUID, fields: Row) -> Row: ...


class ScenesRepo(Protocol):
    async def list(self, production_id: UUID, episode_id: UUID | None = None) -> list[Row]: ...
    async def get(self, production_id: UUID, scene_id: UUID) -> Row | None: ...
    async def update(self, scene_id: UUID, fields: Row) -> Row: ...


class ShotsRepo(Protocol):
    async def get(self, production_id: UUID, shot_id: UUID) -> Row | None: ...
    async def update(self, shot_id: UUID, fields: Row) -> Row: ...
    # A re-fitted scene: delete `removed`, then upsert `shots` (ids kept; numbering is unique
    # again at the end of the statement, so one upsert may renumber).
    async def save_plan(self, shots: list[Row], removed: list[str]) -> None: ...
    async def list(self, production_id: UUID, scene_id: UUID | None = None) -> list[Row]: ...


class LinesRepo(Protocol):
    async def upsert(self, rows: list[Row]) -> None: ...
    async def delete(self, line_ids: list[str]) -> None: ...
    async def list_for_production(self, production_id: UUID) -> list[Row]: ...  # id, shot_id, character_id
    async def list(self, scene_id: UUID) -> list[Row]: ...


class PersonasRepo(Protocol):
    async def get_many(self, persona_ids: list[UUID]) -> list[Row]: ...
    async def list(self) -> list[Row]: ...  # active personas


class BoardRepo(Protocol):
    async def replace(self, production_id: UUID, seats: list[Row], added_by: UUID) -> None: ...
    async def list(self, production_id: UUID) -> list[Row]: ...  # {seat, persona_id, persona: {...}}


class ThreadsRepo(Protocol):
    async def get(self, production_id: UUID, thread_id: UUID) -> Row | None: ...
    async def create(self, fields: Row) -> Row: ...
    async def touch(self, thread_id: UUID) -> None: ...
    async def list(self, production_id: UUID, scene_id: UUID | None = None) -> list[Row]: ...


class MessagesRepo(Protocol):
    async def create(self, fields: Row) -> Row: ...
    async def get(self, production_id: UUID, message_id: UUID) -> Row | None: ...
    async def update(self, message_id: UUID, fields: Row) -> Row: ...
    async def list(self, thread_id: UUID, limit: int = 100) -> list[Row]: ...  # oldest first
    async def clear(self, thread_id: UUID) -> None: ...  # every message of the thread


class SableRepo(Protocol):
    """Sable's threads (plan/2026-11-08 §4.8): rows of `chat_threads` with `chat = 'sable'` and no scene, one person's
    each (`created_by`). Zora's and the classic chat's threads are `chat = 'scene'` (the column's default) and are
    listed by scene, so neither list can show a Sable thread. Messages go through `MessagesRepo`. Schema v18."""

    async def threads(self, production_id: UUID, user_id: UUID) -> list[Row]: ...  # newest first
    async def thread(self, production_id: UUID, thread_id: UUID) -> Row | None: ...  # a Sable thread only
    async def create(self, fields: Row) -> Row: ...
    async def delete(self, thread_id: UUID) -> None: ...  # the thread and its messages


class MemoryRepo(Protocol):
    async def get(self, production_id: UUID, item_id: UUID) -> Row | None: ...
    # Stores the item and indexes it in `chunks` (corpus 'memory', source 'memory:<id>').
    async def add(self, item: Row, embedding: list[float] | None, embedding_model: str) -> Row: ...
    async def delete(self, item_id: UUID) -> None: ...  # the item and its chunk
    async def list(self, production_id: UUID, scene_id: UUID | None = None) -> list[Row]: ...


class DirectionRepo(Protocol):
    """`production_memory` (schema v12, plan/2026-11-05d): what a production's documents say about how to make it. The
    API only reads one entry and changes its status (a person removes one from a reply's chips, plan/2026-11-07)."""

    async def get(self, production_id: UUID, entry_id: UUID) -> Row | None: ...  # None also when the table is missing
    async def update(self, entry_id: UUID, fields: Row) -> Row: ...


class CanonRepo(Protocol):
    async def create(self, fields: Row) -> Row: ...
    async def get(self, production_id: UUID, entity_id: UUID) -> Row | None: ...
    async def versions(self, entity_id: UUID) -> list[Row]: ...
    async def update(self, entity_id: UUID, fields: Row) -> Row: ...
    async def add_version(self, entity_id: UUID, version: Row) -> Row: ...
    async def list(self, production_id: UUID) -> list[Row]: ...


class LooksRepo(Protocol):
    async def list_for_production(self, production_id: UUID) -> list[Row]: ...  # every character's, oldest first
    async def list(self, entity_id: UUID) -> list[Row]: ...  # oldest first
    async def get(self, entity_id: UUID, look_id: UUID) -> Row | None: ...
    async def create(self, fields: Row) -> Row: ...
    async def update(self, look_id: UUID, fields: Row) -> Row: ...
    async def delete(self, look_id: UUID) -> None: ...


class SceneLooksRepo(Protocol):
    async def list(self, scene_id: UUID) -> list[Row]: ...  # entity_id, look_id
    # One look per character per scene: a second pick replaces the first.
    async def choose(self, fields: Row) -> Row: ...
    async def clear(self, scene_id: UUID, entity_id: UUID) -> None: ...


class QuestionsRepo(Protocol):
    async def list(self, production_id: UUID, status: str | None = None) -> list[Row]: ...
    async def get(self, production_id: UUID, question_id: UUID) -> Row | None: ...
    async def answer(self, question_id: UUID, answer: Row, user_id: UUID) -> Row | None: ...
    async def open_count(self, job_id: UUID) -> int: ...


class FramesRepo(Protocol):
    async def create_many(self, rows: list[Row]) -> None: ...
    async def get(self, production_id: UUID, frame_id: UUID) -> Row | None: ...
    async def list_for_shots(self, shot_ids: list[str]) -> list[Row]: ...  # oldest first
    async def update_many(self, frame_ids: list[str], fields: Row) -> None: ...
    # Moves the shot's one accepted frame OF THAT STAGE (`final` unless a draft is meant) to `frame_id`
    # (False: someone accepted another meanwhile).
    async def accept(self, shot_id: UUID, frame_id: UUID, user_id: UUID, stage: str = "final") -> bool: ...
    async def unaccept(self, frame_id: UUID) -> None: ...
    # Frames still queued/running whose row has not changed since `before` (the sweeper; columns id, job_id,
    # updated_at).
    async def active_before(self, before: datetime) -> list[Row]: ...
    # id, shot_id, status, updated_at
    async def live(self, production_id: UUID, since: datetime | None) -> list[Row]: ...


class PromptsRepo(Protocol):
    async def latest_for_shots(self, shot_ids: list[str]) -> dict[str, Row]: ...
    async def list(self, shot_id: UUID) -> list[Row]: ...  # newest first


class TakesRepo(Protocol):
    async def create(self, row: Row) -> Row: ...
    async def get(self, production_id: UUID, take_id: UUID) -> Row | None: ...
    async def list_for_shots(self, shot_ids: list[str]) -> list[Row]: ...  # oldest first
    async def update(self, take_id: UUID, fields: Row) -> Row: ...
    # Moves the shot's one accepted take to `take_id` (False: another was accepted meanwhile).
    async def accept(self, shot_id: UUID, take_id: UUID, user_id: UUID) -> bool: ...


class RendersRepo(Protocol):
    async def create_many(self, rows: list[Row]) -> None: ...
    async def get(self, production_id: UUID, render_id: UUID) -> Row | None: ...
    async def list_for_shots(self, shot_ids: list[str]) -> list[Row]: ...  # oldest first
    async def update_many(self, render_ids: list[str], fields: Row) -> None: ...
    # Renders of the production that are queued or running (the per-production cap on spending).
    async def count_active(self, production_id: UUID) -> int: ...
    # Renders still queued/running whose row has not changed since `before` (the sweeper; columns id, job_id,
    # updated_at).
    async def active_before(self, before: datetime) -> list[Row]: ...
    # id, shot_id, status, updated_at
    async def live(self, production_id: UUID, since: datetime | None) -> list[Row]: ...


class RevisionsRepo(Protocol):
    """`scene_plan_revisions` (schema v14, plan/2026-11-06e §4.7), read only: the zora_chat function writes them. A
    database without the table answers [] (the panel then says undo is not available)."""

    async def list(self, scene_id: UUID) -> list[Row]: ...  # oldest first, without the stored plan


class UsageRepo(Protocol):
    async def record(self, row: Row) -> None: ...
    async def tokens_since(self, since: datetime) -> int: ...
    async def budget(self, month: str) -> int | None: ...  # month: "YYYY-MM-01"
    async def set_budget(self, month: str, tokens: int, user_id: UUID) -> None: ...


class CostsRepo(Protocol):
    """What a scene's cost is worked out from (plan/2026-11-06d). Money is never stored: these return metered usage and
    the dated price list, and `contracts.costs` does the arithmetic."""

    # Every price row, newest first. [] when the table is missing (a database before schema v17).
    async def prices(self) -> list[Row]: ...
    async def add_price(self, row: Row) -> Row: ...
    # `token_usage` rows for one scene: those that name it, and (older rows, legacy engines) those of a job whose
    # request
    # named exactly that scene.
    async def scene_usage(self, production_id: UUID, scene_id: UUID) -> list[Row]: ...
    # Rows of a production tied to no scene whose phase starts with one of `prefixes`: whole-episode work that every
    # scene shares (a job that named a scene is not here).
    async def unassigned_usage(self, production_id: UUID, prefixes: tuple[str, ...]) -> list[Row]: ...
    # The newest rows of a phase prefix, newest first; `production_id` None = across productions.
    async def recent_usage(self, production_id: UUID | None, prefix: str, limit: int) -> list[Row]: ...
    # Dialogue lines per scene of the production (scene id -> count).
    async def lines_by_scene(self, production_id: UUID) -> dict[str, int]: ...


class PacketsRepo(Protocol):
    """A scene's packet (plan/2026-11-11 §7, schema v21 `scene_packets`), written by the structure_build function.
    `None` when the scene has none or the table is missing (a database before v21)."""

    async def get(self, production_id: UUID, scene_id: UUID) -> Row | None: ...


